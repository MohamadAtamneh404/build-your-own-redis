// A helpful alias so we don't have to type std::vector<uint8_t> over and over
typedef vector<uint8_t> Buffer;
enum {
  TAG_NIL = 0, // nil (like null)
  TAG_ERR = 1, // error code + msg
  TAG_STR = 2, // string
  TAG_INT = 3, // int64
  TAG_DBL = 4, // double
  TAG_ARR = 5, // array
};
// Macro to find the starting address of a struct, given the address of one of
// its members. This is heavily used in C (like in the Linux kernel) to simulate
// object-oriented inheritance. We use it here because the hashtable only knows
// about `HNode`, but we need to get back to our actual `Entry` struct that
// contains the string data.
#define container_of(ptr, T, member) ((T *)((char *)ptr - offsetof(T, member)))

// Get the current time in microseconds
static uint64_t get_monotonic_usec() {
  timespec tv = {0, 0};
  clock_gettime(CLOCK_MONOTONIC, &tv);
  return uint64_t(tv.tv_sec) * 1000000 + tv.tv_nsec / 1000;
}

static void msg(const char *msg) { fprintf(stderr, "%s\n", msg); }

static void msg_errno(const char *msg) {
  fprintf(stderr, "[errno:%d] %s\n", errno, msg);
}

static void die(const char *msg) {
  fprintf(stderr, "[%d] %s\n", errno, msg);
  abort();
}

static void fd_set_nb(int fd) {
  errno = 0;
  int flags = fcntl(fd, F_GETFL, 0);
  if (errno) {
    die("fcntl error");
    return;
  }

  flags |= O_NONBLOCK;

  errno = 0;
  (void)fcntl(fd, F_SETFL, flags);
  if (errno) {
    die("fcntl error");
  }
}

const size_t k_max_msg = 32 << 20; // likely larger than the kernel buffer

struct Conn {
  int fd = -1;
  // application's intention, for the event loop
  bool want_read = false;
  bool want_write = false;
  bool want_close = false;
  // buffered input and output
  vector<uint8_t> incoming; // data to be parsed by the application
  vector<uint8_t> outgoing; // responses generated by the application
  uint64_t idle_start = 0;  // The exact microsecond this client connected
  struct DList idle_node;
};
// The massive Global Line where active connections wait
static struct DList g_idle_list;

// Helper function to renew a connection's timer
static void conn_put_idle(Conn *conn) {
  conn->idle_start = get_monotonic_usec();
  dlist_detach(&conn->idle_node); // remove from current position (if any)
  dlist_insert_before(
      &g_idle_list, &conn->idle_node); // put them at the very back of the line
}

const uint64_t k_idle_timeout_ms = 5 * 1000; // 5 seconds

// Calculate how long until the NEXT timer expires
static uint32_t next_timer_ms() {
  if (dlist_empty(&g_idle_list)) {
    return 10000; // default to 10s if nobody is connected
  }
  uint64_t now_us = get_monotonic_usec();
  Conn *next =
      container_of(g_idle_list.next, Conn,
                   idle_node); // Check the guy at the FRONT of the line
  uint64_t next_us = next->idle_start + k_idle_timeout_ms * 1000;
  if (next_us <= now_us) {
    return 0; // The timer has already expired! Wake up instantly.
  }
  return (uint32_t)((next_us - now_us) / 1000);
}

// The Grim Reaper: Check if anyone's timer has expired, and close their
// connection!
static void process_timers() {
  uint64_t now_us = get_monotonic_usec();
  while (!dlist_empty(&g_idle_list)) {
    Conn *next = container_of(g_idle_list.next, Conn, idle_node);
    uint64_t next_us = next->idle_start + k_idle_timeout_ms * 1000;
    if (next_us >= now_us + 1000) {
      break; // The guy at the front of the line isn't expired yet. Everyone
             // else is safe. Stop here!
    }
    printf("removing idle connection: %d\n", next->fd);
    next->want_close = true;        // Mark the connection for deletion
    dlist_detach(&next->idle_node); // Remove them from the timer line so we
                                    // don't process them again
  }
}

// append to the back
static void buf_append(vector<uint8_t> &buf, const uint8_t *data, size_t len) {
  buf.insert(buf.end(), data, data + len);
}

// remove from the front
static void buf_consume(vector<uint8_t> &buf, size_t n) {
  buf.erase(buf.begin(), buf.begin() + n);
}
