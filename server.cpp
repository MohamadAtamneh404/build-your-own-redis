static void buf_append_u8(Buffer &buf, uint8_t data) { buf.push_back(data); }
static void buf_append_u32(Buffer &buf, uint32_t data) {
  buf_append(buf, (const uint8_t *)&data, 4); // assume little-endian
}
static void buf_append_i64(Buffer &buf, int64_t data) {
  buf_append(buf, (const uint8_t *)&data, 8); // assume little-endian
}

// Write a NULL/NIL value
static void out_nil(Buffer &out) { buf_append_u8(out, TAG_NIL); }

// Write a String
static void out_str(Buffer &out, const string &val) {
  buf_append_u8(out, TAG_STR);
  buf_append_u32(out, (uint32_t)val.size());
  buf_append(out, (const uint8_t *)val.data(), val.size());
}

// Write a 64-bit Integer
static void out_int(Buffer &out, int64_t val) {
  buf_append_u8(out, TAG_INT);
  buf_append_i64(out, val);
}

// Write an Error
static void out_err(Buffer &out, int32_t code, const string &msg) {
  buf_append_u8(out, TAG_ERR);
  buf_append_u32(out, (uint32_t)code);
  buf_append_u32(out, (uint32_t)msg.size());
  buf_append(out, (const uint8_t *)msg.data(), msg.size());
}

// Write an Array (just the header, you loop to write items later)
static void out_arr(Buffer &out, uint32_t n) {
  buf_append_u8(out, TAG_ARR);
  buf_append_u32(out, n);
}
